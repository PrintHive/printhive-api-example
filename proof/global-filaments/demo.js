window.runGlobalDemo = async ({ archive, rehearse = false }) => {
  const pause = ms => new Promise(resolve => setTimeout(resolve, rehearse ? Math.min(ms, 100) : ms));
  const get = selector => {
    const node = selector.startsWith('text:') ? [...document.querySelectorAll('button')].find(e => e.textContent.trim() === selector.slice(5)) : document.querySelector(selector);
    if (!node) throw new Error(`Missing ${selector}`);
    return node;
  };
  const until = async predicate => { for (let i = 0; i < 150; i++) { if (predicate()) return; await new Promise(resolve => setTimeout(resolve, 100)); } throw new Error(`Global demo state missing after ${window.globalDemoAction}`); };
  document.querySelectorAll('#demo-cursor,#demo-subtitle').forEach(e => e.remove());
  const cursor = document.createElement('div'); cursor.id = 'demo-cursor';
  cursor.innerHTML = '<svg width="24" height="24" viewBox="0 0 24 24"><path d="M5 3L19 12L12 13L9 20L5 3Z" fill="white" stroke="black" stroke-width="1.5"/></svg>';
  cursor.style.cssText = 'position:fixed;z-index:99999;pointer-events:none;left:10px;top:10px;transition:all .35s'; document.body.append(cursor);
  const caption = document.createElement('div'); caption.id = 'demo-subtitle';
  caption.style.cssText = 'position:fixed;bottom:0;left:0;right:0;z-index:99998;background:#111e;color:white;text-align:center;padding:10px;font:13px system-ui;pointer-events:none'; document.body.append(caption);
  const say = async text => { caption.textContent = `Local mock only. ${text}`; await pause(1500); };
  const view = async selector => { get(selector).scrollIntoView({ behavior: rehearse ? 'instant' : 'smooth', block: 'center' }); await pause(700); const b = get(selector).getBoundingClientRect(); cursor.style.left = `${b.x + b.width / 2}px`; cursor.style.top = `${b.y + b.height / 2}px`; await pause(350); };
  const click = async selector => { window.globalDemoAction = selector; await view(selector); const node = get(selector); if (node.disabled) throw new Error(`Disabled ${selector}`); node.click(); await pause(650); };
  const type = async (selector, text) => { await view(selector); const node = get(selector); node.focus(); const setter = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; setter.call(node, ''); node.dispatchEvent(new Event('input', { bubbles: true })); for (const letter of text) { setter.call(node, node.value + letter); node.dispatchEvent(new Event('input', { bubbles: true })); await pause(35); } await pause(350); };

  await until(() => document.querySelector('#file'));
  await say('Step 1 - Published SDK 0.4.1'); await view('#sdk-info');
  if (!get('#sdk-info').textContent.includes('0.4.1')) throw new Error('Wrong SDK');
  const transfer = new DataTransfer(); transfer.items.add(new File([Uint8Array.from(atob(archive), c => c.charCodeAt(0))], 'shared.3mf', { type: 'model/3mf' }));
  get('#file').files = transfer.files; get('#file').dispatchEvent(new Event('change', { bubbles: true }));
  await until(() => document.querySelector('[aria-label="Configure plate 7"]'));
  await click('[aria-label="Include plate 7"]');
  await click('[aria-label="Configure plate 2"]');
  await say('Step 2 - Search and select a global catalog filament');
  await until(() => document.querySelector('#search-2-0'));
  await type('#search-2-0', 'black PETG'); await click('text:Search');
  await until(() => [...document.querySelectorAll('button')].some(b => b.textContent.trim() === 'Use Generic PETG-CF'));
  await view('text:Use Generic PETG-CF'); await pause(1800);
  await click('text:Use Generic PETG-CF');
  await click('[aria-label="Apply to selected plates using source slot 0"]');
  await click('#confirm-usage');
  await click('[aria-label="Configure plate 7"]');
  if (!get('#filaments').textContent.includes('Requirement: Generic Generic PETG-CF')) throw new Error('Global choice was not copied');
  await click('#confirm-usage');
  await say('Step 3 - Preview both plate requests with global IDs');
  await click('#preview'); await until(() => get('#payload').textContent.includes('"plate": 7'));
  const payload = JSON.parse(get('#payload').textContent);
  const expected = { plates: [2, 7].map(plate => ({ plate, filaments: [{ sourceSlot: 0, filamentId: '44444444-4444-4444-8444-444444444444' }] })) };
  if (JSON.stringify(payload.plates) !== JSON.stringify(expected.plates)) throw new Error(JSON.stringify(payload));
  await view('#payload'); await pause(2000);
  await say('Step 4 - Submit to the mock and wait for manual review');
  await click('#submit'); await until(() => document.querySelector('#state')?.textContent === 'held');
  await view('#state'); await pause(2000);
  await until(() => [...document.querySelectorAll('button')].some(button => button.textContent.trim() === 'Plate 7 · held'));
  await click('text:Plate 7 · held'); await view('#state'); await pause(1800);
  const result = { payload, state: get('#state').textContent, overflow: document.documentElement.scrollWidth > innerWidth, sdk: get('#sdk-info').textContent };
  if (result.overflow) throw new Error('Horizontal overflow');
  return result;
};
