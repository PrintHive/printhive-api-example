window.runPlateDemo = async ({ archive, rehearse = false }) => {
  const pause = ms => new Promise(r => setTimeout(r, rehearse ? Math.min(ms, 120) : ms));
  const until = async predicate => { for (let i = 0; i < 150; i++) { if (predicate()) return; await new Promise(r => setTimeout(r, 100)); } throw new Error(`Plate demo state did not arrive after ${window.plateDemoAction}`); };
  const get = selector => {
    const el = selector.startsWith('text:') ? [...document.querySelectorAll('button')].find(e => e.textContent.trim() === selector.slice(5)) : document.querySelector(selector);
    if (!el) throw new Error(`Missing demo element: ${selector}`);
    return el;
  };
  document.querySelectorAll('#demo-cursor,#demo-subtitle').forEach(el => el.remove());
  const cursor = document.createElement('div'); cursor.id = 'demo-cursor';
  cursor.innerHTML = '<svg width="24" height="24" viewBox="0 0 24 24"><path d="M5 3L19 12L12 13L9 20L5 3Z" fill="white" stroke="black" stroke-width="1.5"/></svg>';
  cursor.style.cssText = 'position:fixed;z-index:99999;pointer-events:none;left:10px;top:10px;transition:all .35s'; document.body.append(cursor);
  const caption = document.createElement('div'); caption.id = 'demo-subtitle';
  caption.style.cssText = 'position:fixed;bottom:0;left:0;right:0;z-index:99998;background:#111e;color:white;text-align:center;padding:10px;font:13px system-ui;pointer-events:none'; document.body.append(caption);
  const say = async text => { caption.textContent = `Local HTTP mock. Synthetic saved previews. ${text}`; await pause(1500); };
  const view = async selector => { const el = get(selector); el.scrollIntoView({ behavior: rehearse ? 'instant' : 'smooth', block: 'center' }); await pause(700); const b = el.getBoundingClientRect(); cursor.style.left = `${b.x + b.width / 2}px`; cursor.style.top = `${b.y + b.height / 2}px`; await pause(350); return el; };
  const click = async selector => { window.plateDemoAction = selector; await view(selector); const el = get(selector); if (el.disabled) throw new Error(`Disabled: ${selector}`); el.click(); await pause(600); };
  const hasButton = text => [...document.querySelectorAll('button')].some(e => e.textContent.trim() === text);
  await until(() => document.querySelector('[aria-label="Configure plate 1"]'));
  await say('Step 1 - Missing previews remain selectable');
  await view('[aria-label="Configure plate 1"]'); await pause(1100);
  await say('Step 2 - Select the plates to submit');
  const input = get('#file');
  const transfer = new DataTransfer(); transfer.items.add(new File([Uint8Array.from(atob(archive), c => c.charCodeAt(0))], 'valid.3mf', { type: 'model/3mf' }));
  input.files = transfer.files; input.dispatchEvent(new Event('change', { bubbles: true }));
  await until(() => document.querySelector('img[alt="Saved preview of plate 7"]')?.naturalWidth > 0);
  await view('[aria-label="Project plates"]'); await pause(1500);
  await click('[aria-label="Include plate 7"]');
  await say('Step 3 - Map each plate independently');
  await click('[aria-label="Configure plate 2"]'); await click('#confirm-usage');
  await until(() => hasButton('Use Red PETG')); await click('text:Use Red PETG');
  await click('[aria-label="Configure plate 7"]'); await click('#confirm-usage');
  await until(() => hasButton('Use Blue PETG')); await click('text:Use Blue PETG');
  await click('[aria-label="Include plate 7"]'); await view('[aria-label="Project plates"]'); await pause(1000);
  await click('[aria-label="Configure plate 7"]');
  if (get('[aria-label="Include plate 7"]').getAttribute('aria-checked') !== 'false') throw new Error('Editing silently included a plate');
  await pause(1000);
  await click('[aria-label="Include plate 7"]');
  if (!document.body.innerText.includes('Requirement: Bambu Blue PETG')) throw new Error('Plate mapping was lost');
  await say('Step 4 - Preview and submit both plates once');
  await click('#preview'); await until(() => get('#payload').textContent.includes('"plate": 7')); await view('#payload'); await pause(1800);
  await click('#submit'); await until(() => hasButton('Plate 2 · held') && hasButton('Plate 7 · held'));
  await view('text:Plate 2 · held'); await pause(1200);
  await say('Step 5 - Release plate 2, cancel plate 7');
  await click('#release'); await until(() => hasButton('Plate 2 · created'));
  await view('#state'); await pause(1200);
  await click('text:Plate 7 · held'); await click('#cancel'); await until(() => hasButton('Plate 7 · cancelled'));
  await view('text:Plate 7 · cancelled'); await pause(1500); await view('#state'); await pause(1600);
  const result = { plate2Created: hasButton('Plate 2 · created'), plate7Cancelled: hasButton('Plate 7 · cancelled'), overflow: document.documentElement.scrollWidth > innerWidth };
  if (result.overflow || !result.plate2Created || !result.plate7Cancelled) throw new Error(JSON.stringify(result));
  return result;
};
