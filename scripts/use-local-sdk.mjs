import { spawnSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, basename, join } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const argument = process.argv[2];
if (!argument || process.argv.length !== 3 || !argument.endsWith('.tgz')) throw new Error('Usage: npm run sdk:local -- /path/to/printhive-api-0.3.0.tgz');
const archive = resolve(argument);
const bytes = await readFile(archive);
const result = spawnSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['install', '--no-save', '--package-lock=false', archive], { cwd: root, stdio: 'inherit', shell: false });
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);
const { installedSdkVersion } = await import('../src/sdk-info.mjs');
const version = installedSdkVersion();
const { PrintHive } = await import('@printhive/api');
const { hasCatalogSync } = await import('../src/catalog-sync.mjs');
if (!hasCatalogSync(new PrintHive({ apiKey: 'local-sdk-capability-check', baseUrl: 'http://127.0.0.1:1' }))) throw new Error('The installed package does not provide filamentCatalog upsert/list/get; no local SDK marker was written');
await mkdir(join(root, 'data'), { recursive: true, mode: 0o700 });
await writeFile(join(root, 'data/sdk-local.json'), JSON.stringify({ kind: 'local-sdk-package', version, archive: basename(archive), sha256: createHash('sha256').update(bytes).digest('hex') }, null, 2)+'\n', { mode: 0o600 });
console.log(`Installed local @printhive/api ${version}; registry dependency and lockfile were not changed.`);
